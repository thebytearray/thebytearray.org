// Generates the Material 3 color roles (light + dark) from the seed in
// src/styles/seed.json and writes them to src/styles/tokens.generated.css.
// The `alternates` in seed.json become extra palettes that visitors can pick
// on the home page; each is selected with `data-color="<name>"` on <html>.
// Run with `npm run tokens` (also runs before dev and build).
import { readFileSync, writeFileSync } from 'node:fs';
import {
  Hct,
  MaterialDynamicColors,
  SchemeTonalSpot,
  argbFromHex,
  hexFromArgb,
} from '@material/material-color-utilities';

const seedFile = new URL('../src/styles/seed.json', import.meta.url);
const outFile = new URL('../src/styles/tokens.generated.css', import.meta.url);

const { seed, alternates = {} } = JSON.parse(readFileSync(seedFile, 'utf8'));
for (const hex of [seed, ...Object.values(alternates)]) {
  if (!/^#[0-9a-f]{6}$/i.test(hex)) {
    throw new Error(`seed.json: "${hex}" is not a 6-digit hex color`);
  }
}

const roles = [
  'primary', 'onPrimary', 'primaryContainer', 'onPrimaryContainer',
  'secondary', 'onSecondary', 'secondaryContainer', 'onSecondaryContainer',
  'tertiary', 'onTertiary', 'tertiaryContainer', 'onTertiaryContainer',
  'error', 'onError', 'errorContainer', 'onErrorContainer',
  'surface', 'onSurface', 'surfaceVariant', 'onSurfaceVariant',
  'surfaceDim', 'surfaceBright',
  'surfaceContainerLowest', 'surfaceContainerLow', 'surfaceContainer',
  'surfaceContainerHigh', 'surfaceContainerHighest',
  'outline', 'outlineVariant',
  'inverseSurface', 'inverseOnSurface', 'inversePrimary',
  'shadow', 'scrim',
];

const kebab = (s) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

function palette(hex, isDark) {
  const scheme = new SchemeTonalSpot(Hct.fromInt(argbFromHex(hex)), isDark, 0);
  return roles.map((role) => [role, hexFromArgb(MaterialDynamicColors[role].getArgb(scheme))]);
}

function declarations(isDark, indent, hex = seed) {
  const base = Object.fromEntries(palette(seed, isDark));
  return palette(hex, isDark)
    // An alternate only lists the roles that differ from the default palette.
    .filter(([role, value]) => hex === seed || value !== base[role])
    .map(([role, value]) => `${indent}--md-sys-color-${kebab(role)}: ${value};`)
    .join('\n');
}

// Alternates come after the default blocks: scripts/generate-assets.mjs and
// src/lib/og.ts read the default colors from the top of the file.
const alternateCss = Object.entries(alternates)
  .map(
    ([name, hex]) => `
/* ${name}: ${hex} */
:root[data-color='${name.toLowerCase()}'] {
${declarations(false, '  ', hex)}
}

:root[data-color='${name.toLowerCase()}'][data-theme='dark'] {
${declarations(true, '  ', hex)}
}
`,
  )
  .join('');

const css = `/* Generated by scripts/generate-tokens.mjs from seed ${seed}. Do not edit. */
:root {
  color-scheme: light;
${declarations(false, '  ')}
}

:root[data-theme='dark'] {
  color-scheme: dark;
${declarations(true, '  ')}
}

/* No-JS fallback: follow the system when the theme script has not run. */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme]) {
    color-scheme: dark;
${declarations(true, '    ')}
  }
}
${alternateCss}`;

writeFileSync(outFile, css);
console.log(`tokens: wrote ${roles.length} color roles for seed ${seed} and ${Object.keys(alternates).length} alternates`);
